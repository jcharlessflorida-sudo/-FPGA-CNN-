#!/usr/bin/env python3
# gen_w2_rom.py — 由 weights/w2.mem 生成 FC1 权重块 RAM 的初值 + 例化模块。
#
# 背景: w2_mem(43264x8b)若用 $readmemh 组合读,会被 TD 推断为分布式 LUT ROM,
# 占 ~20K LUT 放不下。改为显式 PH1P_LOGIC_ERAM(MODE="SP", REGMODE_A="NOREG" 1 周期读)。
# 参照 TD 自带 ROM IP(rom.v)与 RAM 生成器(plugin_mid.tcl):
#   - INIT_FILE 吃 .dat,格式为“二进制逐行”(每行 width 位 MSB-first,位置 = 地址),
#     即 plugin_mid.tcl 里 [format "%0{width}b" val] 的输出。
#   - 20K 块、8bit 宽 → 每块 2048 个条目;43264 / 2048 = 21.125 → 22 块。
#
# 产出:
#   weights/w2_blk_00.dat .. w2_blk_21.dat   (各 2048 行 x 8bit 二进制)
#   cnn_w2_rom.v                              (22 个 ERAM 例化 + 输出 mux)
#
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WEIGHTS_DIR = os.path.join(HERE, "weights")
W2_MEM = os.path.join(WEIGHTS_DIR, "w2.mem")

BLK_DEPTH = 2048
BLK_ADDR_BITS = 11
DATA_WIDTH = 8

HEADER = """// cnn_w2_rom.v - FC1 weight ROM (w2 = 43264x8b), explicit PH1P_LOGIC_ERAM block RAM.
// Auto-generated by gen_w2_rom.py from weights/w2.mem. Do NOT edit by hand.
// 22 blocks x 2048x8 (NOREG 1-cycle read); I_addr[15:11] selects block, [10:0] offset.
// TD synthesis only; ModelSim uses cnn_top.v's `ifdef SIM generic-array branch.
`timescale 1ns/1ps
module cnn_w2_rom (
  input  wire        I_clk,
  input  wire [15:0] I_addr,   // 0..43263
  output wire [7:0]  O_data
);
"""

ERAM_TMPL = """  PH1P_LOGIC_ERAM #(
    .DATA_WIDTH_A({w}), .DATA_WIDTH_B({w}),
    .ADDR_WIDTH_A({a}), .ADDR_WIDTH_B({a}),
    .DATA_DEPTH_A({d}), .DATA_DEPTH_B({d}),
    .MODE("SP"), .REGMODE_A("NOREG"), .REGMODE_B("NOREG"),
    .WRITEMODE_A("NORMAL"), .WRITEMODE_B("NORMAL"),
    .IMPLEMENT("20K(FAST)"),
    .ECC_ENCODE("DISABLE"), .ECC_DECODE("DISABLE"),
    .CLKMODE("ASYNC"),
    .SSROVERCE("DISABLE"),
    .OREGSET_A("RESET"), .OREGSET_B("RESET"),
    .RESETMODE_A("ASYNC"), .RESETMODE_B("ASYNC"),
    .ASYNC_RESET_RELEASE_A("ASYNC"), .ASYNC_RESET_RELEASE_B("ASYNC"),
    .INIT_FILE("weights/w2_blk_{b:02d}.dat"), .FILL_ALL("NONE")
  ) u_blk_{b:02d} (
    .dia({w}'b0), .dib({w}'b0),
    .addra(I_addr[{a_minus}:0]), .addrb({a}'b0),
    .cea(1'b1), .ceb(1'b0),
    .ocea(1'b0), .oceb(1'b0),
    .clka(I_clk), .clkb(1'b0),
    .wea(1'b0), .web(1'b0),
    .bea(1'b0), .beb(1'b0),
    .rsta(1'b0), .rstb(1'b0),
    .ecc_sbiterrinj(1'b0), .ecc_dbiterrinj(1'b0),
    .doa(S_doa[{b}]), .dob(),
    .ecc_sbiterr(), .ecc_dbiterr()
  );
"""


def main():
    with open(W2_MEM, encoding="utf-8") as f:
        vals = [ln.strip() for ln in f if ln.strip()]
    n = len(vals)
    nblocks = (n + BLK_DEPTH - 1) // BLK_DEPTH
    print(f"w2 entries = {n}, blocks = {nblocks}")

    # 1) generate per-block .dat (binary, one width-bit string per line)
    for b in range(nblocks):
        path = os.path.join(WEIGHTS_DIR, f"w2_blk_{b:02d}.dat")
        with open(path, "w", encoding="utf-8") as f:
            for i in range(BLK_DEPTH):
                idx = b * BLK_DEPTH + i
                v = (int(vals[idx], 16) & 0xFF) if idx < n else 0
                f.write(f"{v:0{DATA_WIDTH}b}\n")
        print(f"  wrote {os.path.relpath(path, HERE)}")

    # 2) 生成 cnn_w2_rom.v
    out = [HEADER]
    out.append(f"  wire [{DATA_WIDTH-1}:0] S_doa [0:{nblocks-1}];")
    out.append("")
    for b in range(nblocks):
        out.append(ERAM_TMPL.format(
            w=DATA_WIDTH, a=BLK_ADDR_BITS, d=BLK_DEPTH,
            a_minus=BLK_ADDR_BITS - 1, b=b,
        ))
    out.append("")
    out.append(f"  assign O_data = S_doa[I_addr[15:{BLK_ADDR_BITS}]];")
    out.append("")
    out.append("endmodule\n")

    vpath = os.path.join(HERE, "cnn_w2_rom.v")
    with open(vpath, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"  wrote {os.path.relpath(vpath, HERE)}")


if __name__ == "__main__":
    main()
