#!/usr/bin/env python3
# gen_gamma.py — 生成显示通路的 gamma 校正模块 user_source/hdl_source/gamma_corr.v
#
# 背景: 这条摄像头→ISP→HDMI 参考通路里没有任何 gamma 校正(见分析报告):
#   isp_top.v 只有 demosaic + AWB,RAW10→8 是 >>2 保持线性。
#   线性数据被显示器按 sRGB(≈γ2.2)解释 ⇒ 中间调 L(i) 显示成 L^2.2(i),
#   例如线性 0.5 只有 0.22 的亮度 ⇒ 整幅又暗又灰。
# 修法: 在送 mixer 之前补一级逆变换 out = 255*(i/255)^(1/2.2)。
#
# 黑电平(第 2 轮修复): 上一版只做了 gamma,画面不暗了但"偏灰白"。
#   原因: 传感器的黑电平(SC500 约 0x10 起跳)在 gamma 曲线最陡的一段被放大 ——
#   gam(16) 已经有 72(!),也就是说**本该全黑的像素被抬到中灰**,整幅发灰发白。
#   修法: 查 gamma 表之前先减掉黑电平并重新铺满量程
#       y = max(i - BLACK_LEVEL, 0) * 255 / (255 - BLACK_LEVEL)
#   再查原有的 gamma。
#
#   为什么**折进生成器**而不是在 RTL 里加比较器/乘法器:
#     这个模块坐在 u_video_out → u_hdmi_mixer 的**零延迟区**里,加一级逻辑就有
#     踩爆 75MHz OSD 关键路径的风险(该路径 2026-10-11 实测 SWNS +1.477ns);而折进生成器是**零硬件代价**的
#     —— 预先把复合函数算好,LUT 结构、行数、延迟一个字节都没变。
#     只有 i<=BLACK_LEVEL 的 17 项变成 0,以及全部非零项整体抬升。
#
#   为什么用**精确除法**而不是计划里写的 y + (y>>4) 近似:
#     近似式在 y=239 处只到 253(239+14),会让 gam(255)=253 ≠ 255 ——
#     白场被削、且破坏"端点严格保持"这条不变式(gamma_corr_tb.v 会 FAIL)。
#     精确式在 i=255 处恰好 239*255/239 = 255。
#
# 实现选择(为什么是组合 LUT 而不是 ERAM):
#   mixer 内部把 I_video_de 与 I_video_rd_data 各延迟 3 拍后配对使用,且
#   O_video_rd_en = I_video_de 会反馈去驱动 video_out 读 DDR ⇒ 在 mixer 前面
#   加任何"流水级"都会让数据相对 de 错开 1 拍(延迟 de 会把 rd_en 一起推迟,
#   回来的数据自动跟着走,再叠加额外一级就多 1 拍)。所以这里必须用**零延迟**
#   组合查表:de/user/last 一个都不用动,相位风险归零。
#   代价 3×256×8bit ≈ 6Kbit → TD 映射成约 100 个 LUT6,75MHz 下绰绰有余。
#   (注意: 不能写成 $readmemh + 组合读的大数组——gen_w2_rom.py 的注释里记过,
#    TD 会把可推断数组推成分布式 LUT ROM;256 项虽小,但显式 case 更可控。)
#
# 产出:
#   user_source/hdl_source/gamma_corr.v
#
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "user_source", "hdl_source", "gamma_corr.v")

GAMMA = 1.0 / 2.2          # sRGB 逆变换指数
DEPTH = 256
BLACK_LEVEL = 16           # 传感器黑电平(0..BL 直接判 0)
SPAN = 255 - BLACK_LEVEL   # 去黑后的满量程,用于重新铺满 0..255

HEADER = """// gamma_corr.v - 显示通路 gamma 校正(256x8 LUT x RGB 三通道,纯组合零延迟)。
// Auto-generated by a/gen_gamma.py. Do NOT edit by hand.
// 复合函数: 先去黑电平再 gamma
//   y = max(i - %d, 0) * 255 / %d;   out = round(255 * (y/255)^(1/%s))
// 即 i<=%d -> 0(黑场不抬升), i=255 -> 255(白场不削减)。
//
// 放在 u_video_out 与 u_hdmi_mixer 之间,只接显示通路;CNN 采样仍用原始像素。
// 零延迟是必须的: mixer 的 rd_en(见 hdmi_mixer.v:486 O_video_rd_en = I_video_de)
// 反馈驱动 DDR 读,video_out 的输出与 I_video_de 在引脚上严格同拍,任何额外流水级
// 都会让数据相对 de 错开 1 拍(整幅图水平偏移/撕裂)。
`timescale 1ns/1ps
module gamma_corr (
    input  wire [23:0] I_data,   // RGB888: [23:16]=R [15:8]=G [7:0]=B
    output wire [23:0] O_data
);

  // 三通道共用同一张表,函数在三处被展开成三份 LUT 树。
  function [7:0] gam;
    input [7:0] x;
    begin
      case (x)
""" % (BLACK_LEVEL, SPAN, "2.2", BLACK_LEVEL)


def gam_of(i):
    """复合映射: 去黑电平(重新铺满量程) -> sRGB 逆 gamma。单次取整。"""
    if i <= BLACK_LEVEL:
        return 0                       # 黑场严格归零,不再被 gamma 抬到中灰
    y = (i - BLACK_LEVEL) / float(SPAN)
    v = int(round(255.0 * (y ** GAMMA)))
    return 255 if v > 255 else v


def table_lines():
    out = []
    for i in range(DEPTH):
        out.append("        8'd%-3d: gam = 8'd%d;" % (i, gam_of(i)))
    return out


FOOTER = """        default: gam = 8'd0;
      endcase
    end
  endfunction

  assign O_data = { gam(I_data[23:16]), gam(I_data[15:8]), gam(I_data[7:0]) };

endmodule
"""


def main():
    tb = [gam_of(i) for i in range(DEPTH)]

    # ---- 生成前先自查: 这三条不变式破了,gamma_corr_tb.v 必挂 ----
    assert tb[0] == 0, "黑场被抬起: gam(0)=%d" % tb[0]
    assert tb[255] == 255, "白场被削减: gam(255)=%d" % tb[255]
    # 去黑电平后,整个 0..BLACK_LEVEL 必须严格为 0,否则"偏灰白"没修掉。
    for i in range(BLACK_LEVEL + 1):
        assert tb[i] == 0, "黑电平段未归零: gam(%d)=%d" % (i, tb[i])
    assert all(tb[i] <= tb[i + 1] for i in range(DEPTH - 1)), "曲线非单调,画面会出反相/色带"

    txt = HEADER + "\n".join(table_lines()) + "\n" + FOOTER
    # 必须显式 utf-8: Python 3.6 on Windows 默认按 cp936(GBK) 写,而本工程其余
    # 源文件(video_to_cnn.v / cnn_w2_rom.v ...)都是 UTF-8,混用会让注释变乱码。
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(txt)
    print("wrote %s (%d entries, gamma 1/%.1f, BLACK_LEVEL=%d)"
          % (OUT, DEPTH, 1.0 / GAMMA, BLACK_LEVEL))
    print("  invariants OK: gam(0)=0, gam(255)=255, gam(0..%d)=0, monotonic" % BLACK_LEVEL)
    print("  contrast: gam(%d) = %d (旧版 = %d, 黑电平被 gamma 抬成了中灰)"
          % (BLACK_LEVEL, tb[BLACK_LEVEL],
             int(round(255.0 * (BLACK_LEVEL / 255.0) ** GAMMA))))
    print("  mid-tone: gam(64) = %d (旧版 136)" % tb[64])
    # ---- 供 gamma_corr_tb.v 抽点比对用(改表后必须同步更新 TB 里的期望值)----
    print("  TB spot checks: %s" % ", ".join(
        "gam(%d)=%d" % (i, tb[i]) for i in (0, 1, 17, 32, 64, 96, 100, 128, 160, 192, 200, 224, 240, 255)))


if __name__ == "__main__":
    main()
