#!/usr/bin/env python3
# gen_logo_rom_eram.py — 把 logo 表搬进 PH1P_LOGIC_ERAM(块 RAM),彻底移出 fabric。
#
# 为什么还要再搬一次(2026-10-12 实测):2× 降采样把 logo 的组合 case 从 1918 slices
# 降到约 700,违规端点从 136 降到 72、TNS 减半 —— 但 **WNS 几乎没动**(-558 → -577ps)。
# 最差路径 `u_cnn_top/c_step_reg[4] → u_cnn_top/u_mac/mult0_syn_60.y[5]`(Logic Level 9、
# net 占 49%)整条都在 pll_clk_100m 内部,**logo 根本不在路径上**;logo 只能靠分散 slice
# 挤占 MAC/DSP 的落点来坑它。结论:**这条路径对 logo 的"面积"不敏感,只对"有没有"敏感**
# ⇒ 继续降采样没用,只能把 logo 整体移出 fabric。
#
# 关键事实(决定了本脚本的形状):
#   · TD 自带的 ROM IP 模板 ip/depot/ROMF9F0D0P0_1.0/ROM/RTL/rom.v 生成的**就是单个**
#     PH1P_LOGIC_ERAM 实例(全宽 + 全深 + 一个 INIT_FILE),**块映射由 TD 内部完成**
#     —— 不用像 cnn_w2_rom.v 那样手工拼 22 块。
#   · INIT_FILE 吃 .dat:二进制、**每行 width 位 MSB-first、行号即地址**
#     (见 ip/depot/ROMF9F0D0P0_1.0/ROM/Other/plugin_mid.tcl 的 [format "%0${width}b" ...])。
#   · 路径 "weights/xxx.dat" 相对**源文件所在目录**解析 —— cnn_w2_rom.v 放在 cnn/ 下、
#     数据放在 cnn/weights/ 下,这套用法在本工程已验证。本脚本**照抄这个布局**。
#
# 降采样规则**不在这里重写**,而是从 gen_logo_rom.py 导入(单一口径,避免两份实现漂移)。
#
# 产出:
#   user_source/hdl_source/cnn/weights/logo_80x80.dat   8192 行 x 25bit(6400 有效 + 补零)
#   user_source/hdl_source/cnn/logo_rom_eram.v          单个 PH1P_LOGIC_ERAM 例化
#
# 用法(仓库根目录):
#   python a/gen_logo_rom_eram.py
#
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
from gen_logo_rom import load_src, downsample, check, DW, DH   # noqa: E402

HDL_CNN = os.path.join(HERE, "..", "user_source", "hdl_source", "cnn")
DAT_DIR = os.path.join(HDL_CNN, "weights")
DAT_NAME = "logo_80x80.dat"
V_PATH = os.path.join(HDL_CNN, "logo_rom_eram.v")

ADDR_BITS = 13              # 2^13 = 8192 >= 6400(=80x80)
DEPTH = 1 << ADDR_BITS
WIDTH = 25                  # [24]=opacity [23:16]=R [15:8]=G [7:0]=B

HEADER = """// logo_rom_eram.v - 安路 logo(80x80 降采样版)的块 RAM 存放。
// Auto-generated by a/gen_logo_rom_eram.py. Do NOT edit by hand.
//
// 为什么不放 fabric:原厂 ROM 是稀疏组合 case(6387 条非零),TD 为它造全译码器
// 要 ~1918 slices;降到 2× 后仍有 ~700,而这 ~700 个分散 slice 会挤占 CNN MAC/DSP
// 的落点。实测该域最差路径 `c_step_reg → u_mac/mult0_syn_60.y` 对 logo 的**面积不敏感**
// (1918 和 ~700 两个点上都卡在 -0.57ns),只对 logo **在不在 fabric 里**敏感
// ⇒ 只能整体搬进块 RAM。
//
// 内容与 anlogic_logo_rom_half(组合版,由 a/gen_logo_rom.py 生成)逐字相同,
// %(depth)d 个地址里前 %(used)d 个有效,其后补零(25'd0 = 透明)。
// 与全分辨率原厂 ROM 的交叉验证见 cnn/sim/logo_eram_tb.v。
//
// 读延迟:REGMODE_A("NOREG") 实际寄存 1 拍(见 cnn/sim/eram_model.v 头部)
// ⇒ hdmi_mixer.v 里地址取自 **1d 级**(S_x_1d/S_y_1d),与 S_thumb_addr_r 同一约定。
`timescale 1ns/1ps
module logo_rom_eram (
    input  wire        I_clk,
    input  wire [%(amax)d:0] I_addr,     // 0..%(used_minus)d 有效
    output wire [24:0] O_pixel
);

    PH1P_LOGIC_ERAM #(
        .DATA_WIDTH_A(25), .DATA_WIDTH_B(25),
        .ADDR_WIDTH_A(%(abits)d), .ADDR_WIDTH_B(%(abits)d),
        .DATA_DEPTH_A(%(depth)d), .DATA_DEPTH_B(%(depth)d),
        .MODE("SP"), .REGMODE_A("NOREG"), .REGMODE_B("NOREG"),
        .WRITEMODE_A("NORMAL"), .WRITEMODE_B("NORMAL"),
        .IMPLEMENT("20K(FAST)"),
        .ECC_ENCODE("DISABLE"), .ECC_DECODE("DISABLE"),
        .CLKMODE("ASYNC"),
        .SSROVERCE("DISABLE"),
        .OREGSET_A("RESET"), .OREGSET_B("RESET"),
        .RESETMODE_A("ASYNC"), .RESETMODE_B("ASYNC"),
        .ASYNC_RESET_RELEASE_A("ASYNC"), .ASYNC_RESET_RELEASE_B("ASYNC"),
        .INIT_FILE("weights/%(dat)s"), .FILL_ALL("NONE")
    ) u_eram (
        .dia(25'b0), .dib(25'b0),
        .addra(I_addr), .addrb(%(abits)d'b0),
        .cea(1'b1), .ceb(1'b0),
        .ocea(1'b0), .oceb(1'b0),
        .clka(I_clk), .clkb(1'b0),
        .wea(1'b0), .web(1'b0),
        .bea(1'b0), .beb(1'b0),
        .rsta(1'b0), .rstb(1'b0),
        .ecc_sbiterrinj(1'b0), .ecc_dbiterrinj(1'b0),
        .doa(O_pixel), .dob(),
        .ecc_sbiterr(), .ecc_dbiterr()
    );

endmodule
"""


def main():
    px = load_src()
    ds, hull = downsample(px)
    check(px, ds, hull)                      # 与 gen_logo_rom.py 同一套自查

    assert DW * DH <= DEPTH, "表装不下: %d > %d" % (DW * DH, DEPTH)
    for a in ds:
        assert 0 <= a < DW * DH, "输出地址越界: %d" % a

    # ---- .dat:二进制,每行 WIDTH 位 MSB-first,行号 = 地址 ----
    os.makedirs(DAT_DIR, exist_ok=True)
    dat_path = os.path.join(DAT_DIR, DAT_NAME)
    lines = []
    for i in range(DEPTH):
        v = ds.get(i, 0)                     # 6400 之后全部补 0(透明)
        assert 0 <= v < (1 << WIDTH), "值超出 %d bit: %d" % (WIDTH, v)
        lines.append(format(v, "0%db" % WIDTH))
    # 所有行的位宽必须一致,否则 TD 解析 .dat 会错位。
    assert all(len(s) == WIDTH for s in lines), ".dat 行宽不一致"
    with open(dat_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # ---- 回读自检:.dat 必须逐比特还原出同一张表 ----
    with open(dat_path, "r", encoding="utf-8") as f:
        back = [ln.strip() for ln in f]
    assert len(back) == DEPTH, "回读行数不对: %d != %d" % (len(back), DEPTH)
    for i in range(DEPTH):
        v = int(back[i], 2)
        want = ds.get(i, 0)
        assert v == want, "回读不一致 @%d: 0x%x != 0x%x" % (i, v, want)

    with open(V_PATH, "w", encoding="utf-8") as f:
        f.write(HEADER % dict(depth=DEPTH, used=DW * DH, used_minus=DW * DH - 1,
                              abits=ADDR_BITS, amax=ADDR_BITS - 1, dat=DAT_NAME))

    print("wrote %s" % os.path.relpath(dat_path, HERE))
    print("  %d 行 x %d bit (有效 %d 条, 其后补零)" % (DEPTH, WIDTH, len(ds)))
    print("wrote %s" % os.path.relpath(V_PATH, HERE))
    print("  DATA_WIDTH_A=%d, ADDR_WIDTH_A=%d, DATA_DEPTH_A=%d" % (WIDTH, ADDR_BITS, DEPTH))
    print("  self-check OK: 降采样自查 + .dat 逐比特回读一致")
    # 0 号地址在笔画之外(ink 包围盒 x3..76/y17..63),用 TB 里一起抽验:
    print("  TB spot checks: dat(0)=%s  dat(%d)=%s"
          % (format(ds.get(0, 0), "025b"), DW * DH - 1,
             format(ds.get(DW * DH - 1, 0), "025b")))


if __name__ == "__main__":
    main()
