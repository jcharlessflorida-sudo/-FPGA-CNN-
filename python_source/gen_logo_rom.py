#!/usr/bin/env python3
# gen_logo_rom.py — 把原厂安路 logo ROM 2× 降采样,生成 anlogic_logo_rom_half.v
#
# 为什么需要它(2026-10-11 实测):
#   原厂 anlogic_logo_rom.v 是 160x160 x 25bit 的**稀疏组合 case**(25600 个地址里
#   只有 6387 条非零项),TD 为它造 15bit 全译码器 ⇒ 约 1918 slices,把器件利用率
#   从 73.75% 推到 82.79%。利用率一高,CNN MAC 的路由就变差:100MHz 域从 14 个违规
#   端点涨到 136 个(WNS -84ps → -558ps)。最差路径
#   u_cnn_top/c_step_reg[5] → u_mac/mult0_syn_60.y[4] 是 net 占 52% 的**拥塞型**路径,
#   且 place 阶段该域还是 +105ps / 0 违规,route 之后才崩 —— 是拥塞,不是逻辑深。
#   TD 的 place/route 都用默认设置,没有拥塞优化旋钮 ⇒ 只能从源头减逻辑量。
#
# 做法:显示窗口**一个像素都不动**(仍 160x160,位置/大小/LOGO_X 全不变),只把
#   **查表分辨率**降到 80x80 —— 读地址右移 1 位,以 2x2 块状放大显示。
#   组合 case 条目 6387 → 1769,约省 1400 slices(利用率回到 ~76%)。
#     · 不透明位 = 2x2 块内有墨像素的 OR(有墨就保留,不丢笔画)
#     · RGB     = **只对块内有墨像素**求平均(把背景拉进来会冲淡笔画颜色)
#     · 块内无墨 ⇒ 不输出(透明),与源文件的 default: O_pixel = 0 语义一致
#
# 为什么不改原厂文件:本仓库不在 git 下,改坏不可恢复;而且两个文件并存还能让
#   cnn/sim/logo_half_tb.v 拿全分辨率结果当参考 —— 精度是**交叉验证**出来的,
#   不是靠人眼。本脚本永远只读 anlogic_logo_rom.v(输出是另一个文件),
#   不存在"对着自己的输出再降一次"的风险。
#
# 产出:
#   user_source/hdl_source/anlogic_logo_rom_half.v   (module anlogic_logo_rom_half)
#
# 用法(仓库根目录):
#   python a/gen_logo_rom.py
#
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "user_source", "hdl_source", "anlogic_logo_rom.v")
OUT = os.path.join(HERE, "..", "user_source", "hdl_source", "anlogic_logo_rom_half.v")

W, H = 160, 160
SCALE = 2
DW, DH = W // SCALE, H // SCALE          # 80 x 80

# 与 a/logo_rom_stats.py 逐字相同的解析正则 —— 那里已用它算出"6387 条非零 /
# 降采样后 1769 条",本脚本复用同一规则,两边的条目数应当对得上。
rx = re.compile(r"15'd(\d+)\s*:\s*O_pixel\s*=\s*25'h([0-9a-fA-F]+)")


def rgb(v):
    return ((v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF)


def opaque(v):
    return (v >> 24) & 1


def load_src():
    with open(SRC, "r", encoding="utf-8", errors="replace") as f:
        txt = f.read()
    px = {}
    for m in rx.finditer(txt):
        a, v = int(m.group(1)), int(m.group(2), 16)
        assert a < W * H, "源地址越界: %d" % a
        assert a not in px, "源地址重复: %d" % a
        # 源文件的每个列出的条目都带不透明位(black 靠 default 表达),
        # 这条坏了说明工厂文件被改过,后续所有推论作废。
        assert opaque(v), "源条目没有不透明位: addr=%d val=0x%x" % (a, v)
        px[a] = v
    assert px, "没解析到任何条目 —— 正则或源文件格式变了?"
    return px


def downsample(px):
    """2x2 块降采样。返回 (ds, hull):ds 是 addr->25bit, hull 是 addr->块内像素列表。"""
    hull = {}
    for a, v in px.items():
        x, y = a % W, a // W
        hull.setdefault((y // SCALE) * DW + (x // SCALE), []).append(v)

    ds = {}
    for k, vs in hull.items():
        acc = [0, 0, 0]
        for v in vs:
            r, g, b = rgb(v)
            acc[0] += r
            acc[1] += g
            acc[2] += b
        # 只除以"有墨像素个数",不除 4 —— 否则半透明边缘会被背景冲淡。
        r, g, b = (c // len(vs) for c in acc)   # 向下取整,与 logo_rom_stats.py 同规则
        ds[k] = (1 << 24) | (r << 16) | (g << 8) | b
    return ds, hull


def check(px, ds, hull):
    """生成前自查。任一条破了就 assert,绝不静默产出错文件。"""
    for a in ds:
        assert 0 <= a < DW * DH, "输出地址越界: %d" % a
    for a, v in ds.items():
        assert opaque(v), "输出条目缺少不透明位: addr=%d" % a

    # 墨迹无丢失:源里每一个有墨像素所在的块,输出里都必须存在。
    for a in px:
        x, y = a % W, a // W
        k = (y // SCALE) * DW + (x // SCALE)
        assert k in ds, "丢了墨迹: 源 addr=%d (x=%d,y=%d) -> 块 %d 不在输出里" % (a, x, y, k)

    # 颜色落在块内色域:均值必然落在 [min,max] 内 —— 这条验证的是实现本身。
    for k, vs in hull.items():
        v = ds[k]
        for ch, val in enumerate(rgb(v)):
            lo = min(rgb(u)[ch] for u in vs)
            hi = max(rgb(u)[ch] for u in vs)
            assert lo <= val <= hi, \
                "块 %d 通道 %d 越界: %d 不在 [%d,%d]" % (k, ch, val, lo, hi)


def entry_lines(ds):
    # 地址宽度 15 -> 13(80*80 = 6400 项,13bit 足够);按数值排序输出。
    return ["            13'd%-5d: O_pixel = 25'h%x;" % (a, ds[a]) for a in sorted(ds)]


def ascii_preview(ds, step=2):
    """整幅缩略图。每 step 行取一行、列全取 ⇒ 配合终端字符约 2:1 的长宽比看起来大致是方形。"""
    lines = []
    for y in range(0, DH, step):
        lines.append("".join("#" if ds.get(y * DW + x) else "." for x in range(DW)))
    return lines


HEADER = """// anlogic_logo_rom_half.v - 原厂安路 logo 的 2 倍降采样版(80x80 x 25bit 组合 case)。
// Auto-generated by a/gen_logo_rom.py. Do NOT edit by hand.
//
// 由 user_source/hdl_source/anlogic_logo_rom.v (160x160, 6387 条非零项)降采样而来:
//   每个 2x2 块 —— 不透明位取 OR;RGB 只对块内有墨像素求平均(不混入背景)。
//   条目 6387 -> %d;组合 case 的逻辑量随之从约 1918 slices 降到约 %d。
//
// 显示端(hdmi_mixer.v)的用法:窗口仍是 160x160(LOGO_W/LOGO_H 不变),读地址按
//   ((y - LOGO_Y) >> 1) * 80 + ((x - LOGO_X) >> 1)
// 计算,即以 2x2 块状放大显示。地址宽度 15 -> 13。
//
// 与原厂文件的交叉验证见 cnn/sim/logo_half_tb.v(墨迹无丢失 + 颜色落在块内色域)。
`timescale 1ns/1ps
module anlogic_logo_rom_half (
    input wire [12:0] I_addr,   // 0..6399
    output reg [24:0] O_pixel
);

    always @(*) begin
        case(I_addr)
"""

FOOTER = """            default: O_pixel = 25'd0;
        endcase
    end

endmodule
"""


def main():
    px = load_src()
    ds, hull = downsample(px)
    check(px, ds, hull)

    txt = (HEADER % (len(ds), 1918 * len(ds) // len(px))
           + "\n".join(entry_lines(ds)) + "\n" + FOOTER)
    # 必须显式 utf-8:Python 3.6 on Windows 默认按 cp936(GBK) 写,
    # 而本工程其余源文件都是 UTF-8,混用会让注释变乱码。
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(txt)

    xs = [a % DW for a in ds]
    ys = [a // DW for a in ds]
    print("wrote %s" % os.path.basename(OUT))
    print("  源 : %d x %d = %d 地址, 非零 %d" % (W, H, W * H, len(px)))
    print("  输出: %d x %d = %d 地址, 非零 %d (原 %d, %.0f%%)"
          % (DW, DH, DW * DH, len(ds), len(px), 100.0 * len(ds) / len(px)))
    print("  ink 包围盒: x %d..%d  y %d..%d" % (min(xs), max(xs), min(ys), max(ys)))
    print("  slices 估算: 1918 * %d/%d = %d" % (len(ds), len(px), 1918 * len(ds) // len(px)))
    print("  self-check OK: 地址在界内 / 均有不透明位 / 墨迹无丢失 / 颜色落在块内色域")

    # 跑 20 分钟 TD 之前先让人眼过一遍形状。
    print("")
    print("  缩略图(每 2 行取 1 行, 80 列; '#'=有墨):")
    for ln in ascii_preview(ds):
        print("    " + ln)

    # ---- 供 cnn/sim/logo_half_tb.v 抽点比对用(改表后必须同步更新 TB 里的期望值)----
    order = sorted(ds)
    picks = [order[0], order[1], order[len(order) // 4], order[len(order) // 2],
             order[3 * len(order) // 4], order[-2], order[-1]]
    print("")
    print("  TB spot checks: %s" % ", ".join(
        "half(%d)=25'h%x" % (a, ds[a]) for a in picks))


if __name__ == "__main__":
    main()
